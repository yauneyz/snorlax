#!/usr/bin/env node
// Builds native/engine-wasm to wasm and regenerates packages/engine-wasm/pkg:
//   engine.js / engine.d.ts  — wasm-bindgen glue (--target web)
//   wasm-bytes.js           — the module, base64-inlined so every host (Vitest, the bundled
//                             Electron main process, a renderer) loads it without a file path.
// Needs a Rust toolchain with the wasm32-unknown-unknown target and wasm-bindgen-cli matching the
// crate's pinned wasm-bindgen (0.2.127) on PATH. Run with `pnpm build:engine-wasm`; commit pkg/.

import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const crate = path.join(root, 'native/engine-wasm');
const pkg = path.join(root, 'packages/engine-wasm/pkg');
const wasm = path.join(crate, 'target/wasm32-unknown-unknown/release/talysman_engine_wasm.wasm');

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], { cwd: crate, stdio: 'inherit' });
rmSync(pkg, { recursive: true, force: true });
execFileSync('wasm-bindgen', ['--target', 'web', '--out-dir', pkg, '--out-name', 'engine', wasm], { stdio: 'inherit' });

const bytes = readFileSync(path.join(pkg, 'engine_bg.wasm'));
rmSync(path.join(pkg, 'engine_bg.wasm'));
rmSync(path.join(pkg, 'engine_bg.wasm.d.ts'));
writeFileSync(
  path.join(pkg, 'wasm-bytes.js'),
  '// Generated by scripts/build-engine-wasm.mjs. Do not edit.\n' +
    `export default ${JSON.stringify(bytes.toString('base64'))};\n`,
);
writeFileSync(path.join(pkg, 'wasm-bytes.d.ts'), 'declare const bytes: string;\nexport default bytes;\n');
console.log(`packages/engine-wasm/pkg: ${(bytes.length / 1024).toFixed(0)} KiB wasm`);
